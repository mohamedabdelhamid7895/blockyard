/* HTML/CSS generation, shared by the editor canvas, Preview, Export and publishing. */
import { BASE_CSS, BP_ORDER, BREAKPOINTS, GOOGLE_FONT_NAMES, STATES, VOID_TAGS } from './constants';
import { IX_CSS, IX_RUNTIME, ixData, treeHasIx, waitsForEntrance } from './interactions';
import { itemPageFile, templatePageFor, walkAll, walkTree } from './model';
import { A11Y_RUNTIME, abRuntime, COMPONENT_CSS, COMPONENT_RUNTIME, iconSVG } from './widgets';
import type { Collection, Item, Node, Page, Project, StyleMap } from './types';

export const escHTML = (s: string) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
export const escAttr = (s: string) => escHTML(s).replace(/"/g, '&quot;');
const textToHTML = (t: string) => escHTML(t).replace(/\n/g, '<br>');

/* ---- CSS ---- */
const cssDecl = (obj: StyleMap | undefined, pad: string) =>
  Object.entries(obj || {}).filter(([, v]) => v !== '' && v != null).map(([k, v]) => `${pad}${k}: ${v};`).join('\n');

/** Selectors in use: every class chain on an element and each of its classes on its own (imported utility classes). */
function usedSelectors(p: Project) {
  const used = new Set<string>(['body']);
  walkAll(p, (n) => {
    for (let i = 1; i <= n.classes.length; i++) used.add(n.classes.slice(0, i).join('.'));
    n.classes.forEach((c) => used.add(c));
  });
  return used;
}

/**
 * Stylesheet for every selector. In the editor, state styles also match a `__force-<state>`
 * class so the selected element can show its hover/pressed/focused look while being styled.
 */
export function generateCSS(p: Project, { onlyUsed = false, editor = false } = {}) {
  const used = onlyUsed ? usedSelectors(p) : null;
  // Base classes before combos so source order matches specificity intuition.
  const keys = Object.keys(p.classes).filter((k) => !used || used.has(k))
    .sort((a, b) => a.split('.').length - b.split('.').length);
  let out = '';
  for (const bp of BP_ORDER) {
    const media = BREAKPOINTS[bp].media;
    const ind = media ? '  ' : '';
    let block = '';
    for (const key of keys) {
      const sel = '.' + key;
      for (const st of STATES) {
        const decl = cssDecl(p.classes[key][st.id === 'none' ? bp : `${bp}:${st.id}`], ind + '  ');
        if (!decl) continue;
        const selector = st.id === 'none' ? sel : editor ? `${sel}${st.pseudo}, ${sel}.__force-${st.id}` : sel + st.pseudo;
        block += `${ind}${selector} {\n${decl}\n${ind}}\n`;
      }
    }
    if (!block) continue;
    out += media ? `\n@media screen and ${media} {\n${block}}\n` : block;
  }
  return out;
}

const RUNTIME_TYPES = new Set(['navbar', 'tabs', 'slider', 'lightbox', 'bgvideo', 'form']);
function scan(p: Project, roots: Node[]) {
  const found = { ix: false, runtime: false, a11y: false, form: false };
  const seen = new Set<string>();
  const visit = (n: Node) => walkTree(n, (x) => {
    if (x.ix?.length) found.ix = true;
    if (RUNTIME_TYPES.has(x.type)) found.runtime = true;
    if (x.type === 'form') found.form = true;
    if (x.type === 'a11ywidget') found.a11y = true;
    if (x.type === 'symbol' && x.componentId && !seen.has(x.componentId) && p.components[x.componentId]) {
      seen.add(x.componentId);
      visit(p.components[x.componentId].root);
    }
  });
  roots.forEach(visit);
  return found;
}

export const siteUsesIx = (p: Project) => p.pages.some((pg) => treeHasIx(pg.root)) || Object.values(p.components).some((c) => treeHasIx(c.root));

export function siteCSS(p: Project, minify = false) {
  const css = `/* Generated by Blockyard */\n${BASE_CSS}${COMPONENT_CSS}${siteUsesIx(p) ? '\n' + IX_CSS : ''}\n${generateCSS(p, { onlyUsed: true })}`;
  return minify ? minifyCSS(css) : css;
}

export function minifyCSS(css: string) {
  return css.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s+/g, ' ').replace(/\s*([{}:;,>])\s*/g, '$1').replace(/;}/g, '}').trim() + '\n';
}

/** Google Fonts link for only the families the site uses. */
function fontsLink(css: string) {
  const used = GOOGLE_FONT_NAMES.filter((f) => css.includes(f));
  if (!used.length) return '';
  const fam = used.map((f) => `family=${f.replace(/ /g, '+')}:wght@400;500;600;700;800`).join('&');
  return `  <link rel="preconnect" href="https://fonts.googleapis.com">\n  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n  <link rel="stylesheet" href="https://fonts.googleapis.com/css2?${fam}&display=swap">\n`;
}

/* ---- HTML ---- */
export interface RenderCtx {
  p: Project;
  editor: boolean;
  collection?: Collection | null;
  item?: Item | null;
  /** Inside a component instance: inner elements are not individually selectable in the editor. */
  inSymbol?: boolean;
  /** Collection items after the first: same node ids, so they are skipped by drag targets. */
  rep?: boolean;
  /** Position among siblings (tabs use it). */
  index?: number;
  /** Selected tab index inside the nearest Tabs element. */
  tabsCurrent?: number;
  /** Counts images so the first one loads eagerly (it is usually the largest above the fold). */
  images?: { n: number };
  /** Where Blockyard Forms post when a form has no action of its own. */
  formEndpoint?: string;
}

/** Editor-only attributes that never reach the published HTML. */
const PRIVATE_ATTRS = new Set(['data-current', 'data-address', 'data-video', 'data-icon', 'data-dir', 'data-decorative', 'data-success-preview']);

function boundValue(ctx: RenderCtx, field: string | undefined): string | undefined {
  if (!field || !ctx.item || !ctx.collection) return undefined;
  if (field === '__url') return templatePageFor(ctx.p, ctx.collection.id) ? itemPageFile(ctx.collection, ctx.item) : '#';
  return ctx.item.data[field] ?? '';
}

const mapSrc = (address: string) => `https://maps.google.com/maps?q=${encodeURIComponent(address || 'Berlin')}&z=14&output=embed`;

export function renderNode(n: Node, ctx: RenderCtx, depth = 0, nidOverride?: string): string {
  const { p, editor } = ctx;
  const pad = editor ? '' : '  '.repeat(depth);

  if (n.type === 'symbol') {
    const comp = p.components[n.componentId || ''];
    if (!comp) return editor ? `<div data-nid="${n.id}" class="__missing">Missing component</div>` : '';
    const root = n.ix?.length ? { ...comp.root, ix: [...(comp.root.ix || []), ...n.ix] } : comp.root;
    return renderNode(root, { ...ctx, inSymbol: true }, depth, editor ? n.id : undefined);
  }

  const classes = [...n.classes];
  let attrs = '';
  const nid = nidOverride || (ctx.inSymbol ? null : n.id);
  if (editor) {
    if (nid) attrs += ` data-nid="${nid}"`;
    if (nidOverride) attrs += ' data-symbol="1"';
    if (ctx.rep) attrs += ' data-rep="1"';
    if (nid && n.type !== 'body' && !ctx.rep) attrs += ' draggable="true"';
    if (n.bind?.text) attrs += ' data-bound="1"';
    if (n.type === 'srtext') attrs += ' data-editor-sr';
  }

  const a: Record<string, string> = { ...(n.attrs || {}) };
  if (editor && n.tag === 'button') a.type = 'button'; // never submit inside the editor
  const src = boundValue(ctx, n.bind?.src);
  if (src !== undefined) a.src = src;
  const href = boundValue(ctx, n.bind?.href);
  if (href !== undefined) a.href = href;
  const bg = boundValue(ctx, n.bind?.bg);
  if (bg) a.style = `background-image: url("${bg.replace(/"/g, '%22')}")` + (a.style ? '; ' + a.style : '');
  if (!editor && n.ix?.length) {
    a['data-ix'] = ixData(n.ix);
    if (waitsForEntrance(n.ix)) a['data-ix-wait'] = '';
  }

  // Element behaviour and accessibility semantics.
  let childCtx: RenderCtx = ctx;
  let before = '', after = '';
  switch (n.type) {
    case 'navbar': a['data-by'] = 'navbar'; if (editor) a['data-open'] = ''; break;
    case 'navmenu': a['data-by-menu'] = ''; break;
    case 'navbutton': a['data-by-toggle'] = ''; a['aria-expanded'] = 'false'; break;
    case 'tabs': a['data-by'] = 'tabs'; childCtx = { ...ctx, tabsCurrent: Number(n.attrs?.['data-current'] || 0) }; break;
    case 'tabsmenu': a.role = 'tablist'; break;
    case 'tablink': a.role = 'tab'; a['aria-selected'] = String(ctx.index === (ctx.tabsCurrent ?? 0)); break;
    case 'tabpane': a.role = 'tabpanel'; if (ctx.index !== (ctx.tabsCurrent ?? 0)) a.hidden = ''; break;
    case 'slider': a['data-by'] = 'slider'; break;
    case 'slidertrack': a['data-by-track'] = ''; break;
    case 'sliderarrow': a[n.attrs?.['data-dir'] === 'prev' ? 'data-by-prev' : 'data-by-next'] = ''; break;
    case 'lightbox': a['data-by'] = 'lightbox'; break;
    case 'skiplink': a['data-by-skip'] = ''; break;
    case 'map': a.src = mapSrc(n.attrs?.['data-address'] || ''); if (!editor) a.loading = 'lazy'; break;
    case 'video': if (!editor) a.loading = 'lazy'; break;
    case 'icon':
      if (n.attrs?.['aria-label']) a.role = 'img'; else a['aria-hidden'] = 'true';
      break;
    case 'bgvideo': {
      classes.push('by-bgvideo');
      const v = n.attrs?.['data-video'];
      if (v) {
        before = `<video autoplay muted loop playsinline preload="metadata" aria-hidden="true" src="${escAttr(v)}"${editor ? ' style="pointer-events:none"' : ''}></video>`;
        after = editor ? '' : '<button type="button" class="by-video-toggle">Pause video</button>';
      }
      break;
    }
    case 'image':
      if (a['data-decorative'] === 'true') { a.alt = ''; a.role = 'presentation'; }
      if (!editor && ctx.images) {
        const first = ctx.images.n++ === 0;
        if (first) a.fetchpriority = 'high'; else a.loading = 'lazy';
        a.decoding = 'async';
      }
      break;
    case 'form':
      a['data-by-form'] = '';
      if (!a.action) a.action = ctx.formEndpoint || '';
      if (!a.method) a.method = 'post';
      if (!editor) after = '<input type="text" name="_gotcha" tabindex="-1" autocomplete="off" aria-hidden="true" style="position:absolute;left:-9999px">';
      break;
    case 'a11ywidget': a['data-by'] = 'a11y'; break;
  }
  if (!editor) for (const k of PRIVATE_ATTRS) delete a[k];
  for (const [k, v] of Object.entries(a)) {
    if (k === 'data-ix-wait' || k === 'hidden' || k.startsWith('data-by') && v === '' || k === 'data-open'
      || ((k === 'allowfullscreen' || k === 'required') && v === 'true')) attrs += ` ${k}`;
    else if (v !== '' && v != null) attrs += ` ${k}="${escAttr(v)}"`;
    else if (k === 'alt') attrs += ' alt=""';
  }

  const clsList = (extra: string[] = []) => {
    const all = [...classes, ...extra];
    return all.length ? ` class="${all.join(' ')}"` : '';
  };

  if (n.type === 'collectionlist') {
    const coll = p.collections.find((c) => c.id === n.collectionId) || null;
    const tpl = n.children?.[0];
    let inner: string;
    if (!coll) inner = editor ? '<div class="__cms-empty">Choose a collection in the Settings panel</div>' : '';
    else if (!tpl) inner = '';
    else {
      const items = n.limit ? coll.items.slice(0, n.limit) : coll.items;
      inner = items.length
        ? items.map((item, i) => renderNode(tpl, { ...ctx, collection: coll, item, rep: ctx.rep || i > 0 }, depth + 1)).join(editor ? '' : '\n')
        : editor ? '<div class="__cms-empty">No items found.</div>' : `${pad}  <div class="empty-state">No items found.</div>`;
    }
    return editor ? `<${n.tag}${clsList()}${attrs}>${inner}</${n.tag}>` : `${pad}<${n.tag}${clsList()}${attrs}>\n${inner}\n${pad}</${n.tag}>`;
  }

  // Composite elements rendered from their settings.
  if (n.type === 'checkbox' || n.type === 'radio') {
    const at = n.attrs || {};
    const inputAttrs = `type="${n.type}" name="${escAttr(at.name || '')}"${at.value ? ` value="${escAttr(at.value)}"` : ''}${at.required === 'true' ? ' required' : ''}`;
    const outer = attrs.replace(/ (name|value|required)="[^"]*"/g, '').replace(/ required\b/, '');
    return `${pad}<label${clsList()}${outer}><input ${inputAttrs}> <span>${escHTML(n.text || '')}</span></label>`;
  }
  if (n.type === 'select') {
    const opts = (n.options || []).map((o, i) => `<option${i === 0 && /…|\.\.\.|choose|select/i.test(o) ? ' value=""' : ''}>${escHTML(o)}</option>`).join('');
    return `${pad}<select${clsList()}${attrs}>${opts}</select>`;
  }
  if (n.type === 'navbutton') return `${pad}<button${clsList()}${attrs}>${iconSVG('menu')}</button>`;
  if (n.type === 'icon') return `${pad}<span${clsList()}${attrs}>${iconSVG(n.attrs?.['data-icon'] || 'star', 24).replace('width="24" height="24"', 'width="100%" height="100%"')}</span>`;
  if (n.type === 'a11ywidget' && editor) {
    const pos = n.attrs?.['data-position'] || 'bottom-right';
    return `<div${clsList()}${attrs} style="position:fixed;${pos.includes('right') ? 'right' : 'left'}:20px;${pos.includes('bottom') ? 'bottom' : 'top'}:20px;z-index:50;width:56px;height:56px;border-radius:50%;display:grid;place-items:center;color:#fff;background:${escAttr(n.attrs?.['data-color'] || '#146ef5')};box-shadow:0 6px 20px rgba(0,0,0,.25)" title="Accessibility widget (works on the published site)"><svg width="30" height="30" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"><circle cx="12" cy="4" r="2"/><path d="M4 7.5l5.5 1.3V13L7.5 21h2.3l2.2-6 2.2 6h2.3L14.5 13V8.8L20 7.5l-.5-2-6 1.3h-3l-6-1.3z"/></svg></div>`;
  }

  if (editor && n.children && !n.children.length && n.html == null && n.type !== 'body') classes.push('__empty');
  const open = `<${n.tag}${clsList()}${attrs}>`;
  if (VOID_TAGS.has(n.tag)) return pad + open;

  const boundText = boundValue(ctx, n.bind?.text);
  if (boundText !== undefined) return `${pad}${open}${textToHTML(boundText)}</${n.tag}>`;
  if (n.html != null) return editor ? `${open}${n.html}</${n.tag}>` : `${pad}${open}\n${n.html}\n${pad}</${n.tag}>`;
  if (n.text != null) return `${pad}${open}${textToHTML(n.text)}</${n.tag}>`;
  if (!n.children || !n.children.length) return `${pad}${open}${before}${after}</${n.tag}>`;
  const kids = n.children.map((c, i) => renderNode(c, { ...childCtx, index: i }, depth + 1));
  return editor ? open + before + kids.join('') + after + `</${n.tag}>` : `${pad}${open}${before}\n${kids.join('\n')}\n${after}${pad}</${n.tag}>`;
}

/** Inner HTML of a page body. */
export function bodyHTML(p: Project, page: Page, item: Item | null, editor: boolean, formEndpoint = '') {
  const collection = page.collectionId ? p.collections.find((c) => c.id === page.collectionId) || null : null;
  const ctx: RenderCtx = { p, editor, collection, item: collection ? item : null, images: { n: 0 }, formEndpoint };
  return (page.root.children || []).map((c, i) => renderNode(c, { ...ctx, index: i }, 1)).join(editor ? '' : '\n');
}

export interface PageOptions {
  item?: Item | null;
  inlineCSS?: boolean;
  extraHead?: string;
  /** Absolute URL of the published site, for canonical links, social tags and the sitemap. */
  siteUrl?: string;
  /** File name of this page in the site (e.g. "about.html"). */
  fileName?: string;
  minify?: boolean;
  /** Blockyard server API base (e.g. https://app.example.com/api) for forms and A/B tracking. */
  apiBase?: string;
  projectId?: string;
  /** Set when serving one side of an A/B test. */
  ab?: { experimentId: string; variant: 'a' | 'b'; goal: string };
  /** Experiments whose goal is visiting this page. */
  abGoals?: string[];
}

const minifyHTML = (html: string) => html.replace(/>\s+</g, '><').replace(/\n\s*/g, '\n');

export function pageHTML(p: Project, page: Page, o: PageOptions = {}) {
  const item = o.item ?? null;
  const css = siteCSS(p, o.minify);
  const s = p.settings || {};
  const styleTag = o.inlineCSS ? `  <style>\n${css}  </style>\n` : `  <link rel="stylesheet" href="css/styles.css">\n`;
  const title = item ? `${item.data.name} | ${page.title || page.name}` : page.title || page.name;
  const descText = item?.data.summary || page.description;
  const seo = page.seo || {};
  const fileName = o.fileName || `${page.slug}.html`;
  const pageUrl = o.siteUrl ? o.siteUrl.replace(/\/?$/, '/') + (fileName === 'index.html' ? '' : fileName) : '';
  const ogImage = (item?.data.image && /^https?:/.test(item.data.image) ? item.data.image : '') || seo.ogImage || s.ogImage || '';
  const meta: string[] = [];
  if (descText) meta.push(`<meta name="description" content="${escAttr(descText)}">`);
  if (seo.noindex) meta.push('<meta name="robots" content="noindex">');
  if (pageUrl) meta.push(`<link rel="canonical" href="${escAttr(pageUrl)}">`);
  if (s.favicon) meta.push(`<link rel="icon" href="${escAttr(s.favicon)}">`);
  meta.push(`<meta property="og:type" content="${item ? 'article' : 'website'}">`);
  meta.push(`<meta property="og:title" content="${escAttr(seo.ogTitle || title)}">`);
  if (seo.ogDescription || descText) meta.push(`<meta property="og:description" content="${escAttr(seo.ogDescription || descText)}">`);
  if (pageUrl) meta.push(`<meta property="og:url" content="${escAttr(pageUrl)}">`);
  if (s.siteName) meta.push(`<meta property="og:site_name" content="${escAttr(s.siteName)}">`);
  if (ogImage) meta.push(`<meta property="og:image" content="${escAttr(ogImage)}">`);
  meta.push(`<meta name="twitter:card" content="${ogImage ? 'summary_large_image' : 'summary'}">`);
  if (page.slug === 'index' && pageUrl && !item) {
    meta.push(`<script type="application/ld+json">${JSON.stringify({ '@context': 'https://schema.org', '@type': 'WebSite', name: s.siteName || page.title, url: pageUrl })}</script>`);
  }

  const used = scan(p, [page.root]);
  const scripts = [
    used.ix ? IX_RUNTIME : '',
    used.runtime ? COMPONENT_RUNTIME : '',
    o.ab || o.abGoals?.length ? abRuntime(`${o.apiBase || ''}/ab/${o.projectId || ''}`) : '',
  ].join('');
  // Site code first, then page code, as Webflow orders them.
  const code = (where: 'head' | 'body') =>
    [s.customCode?.[where], page.customCode?.[where]].filter((c) => c && c.trim()).map((c) => c!.trim() + '\n').join('');
  const htmlAttrs = [`lang="${escAttr(s.lang || 'en')}"`];
  if (o.ab) htmlAttrs.push(`data-ab="${o.ab.experimentId}:${o.ab.variant}"`, `data-ab-goal="${escAttr(o.ab.goal)}"`);
  if (o.abGoals?.length) htmlAttrs.push(`data-ab-goals="${o.abGoals.join(',')}"`);
  const formEndpoint = o.apiBase && o.projectId ? `${o.apiBase}/forms/${o.projectId}` : '';

  const html = `<!DOCTYPE html>
<html ${htmlAttrs.join(' ')}>
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escHTML(title)}</title>
${meta.map((m) => `  ${m}\n`).join('')}${fontsLink(generateCSS(p, { onlyUsed: true }))}${styleTag}${scripts}${code('head')}${o.extraHead || ''}</head>
<body class="${page.root.classes.join(' ')}">
${bodyHTML(p, page, item, false, formEndpoint)}
${used.a11y ? A11Y_RUNTIME : ''}${code('body')}</body>
</html>
`;
  return o.minify ? minifyHTML(html) : html;
}

/** Every file in the exported site. Template pages produce one file per collection item; A/B variants are left out. */
export interface SiteFile { name: string; page?: Page; item?: Item | null }

export function siteFiles(p: Project): SiteFile[] {
  const out: SiteFile[] = [];
  for (const page of p.pages) {
    if (page.variantOf) continue;
    const coll = page.collectionId ? p.collections.find((c) => c.id === page.collectionId) : null;
    if (coll) coll.items.forEach((item) => out.push({ name: itemPageFile(coll, item), page, item }));
    else if (!page.collectionId) out.push({ name: `${page.slug}.html`, page, item: null });
  }
  return out;
}

export function sitemapXML(p: Project, siteUrl: string) {
  const base = siteUrl.replace(/\/?$/, '/');
  const urls = siteFiles(p).filter((f) => !f.page!.seo?.noindex && !f.page!.seo?.excludeFromSitemap)
    .map((f) => `  <url><loc>${escHTML(base + (f.name === 'index.html' ? '' : f.name))}</loc></url>`);
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join('\n')}\n</urlset>\n`;
}

export interface ExportOptions { siteUrl?: string; minify?: boolean; apiBase?: string; projectId?: string }

export function exportFiles(p: Project, o: ExportOptions = {}) {
  const files = siteFiles(p).map((f) => ({ name: f.name, content: pageHTML(p, f.page!, { ...o, item: f.item, fileName: f.name }) }));
  files.push({ name: 'css/styles.css', content: siteCSS(p, o.minify) });
  if (o.siteUrl) {
    files.push({ name: 'sitemap.xml', content: sitemapXML(p, o.siteUrl) });
    files.push({ name: 'robots.txt', content: `User-agent: *\nAllow: /\n\nSitemap: ${o.siteUrl.replace(/\/?$/, '/')}sitemap.xml\n` });
  }
  return files;
}

/* ---- Publishing (with A/B tests) ---- */
export interface PublishedExperiment { id: string; file: string; variantFile: string; split: number }

const goalAttr = (g: NonNullable<Page['abTest']>['goal']) => (g.type === 'click' ? `click:${g.selector}` : g.type);

/**
 * Files for a published site. Pages with a running A/B test also get their variant at `_ab/<id>.html`;
 * the server picks one side per visitor. Pages that are a test's goal report conversions.
 */
export function publishFiles(p: Project, o: ExportOptions) {
  const experiments: PublishedExperiment[] = [];
  const running = new Map<string, { test: NonNullable<Page['abTest']>; variant: Page }>();
  const goalsByPage = new Map<string, string[]>();
  for (const page of p.pages) {
    const t = page.abTest;
    const variant = t && p.pages.find((x) => x.id === t.variantPageId);
    if (!t || !variant || t.status !== 'running' || page.collectionId) continue;
    running.set(page.id, { test: t, variant });
    if (t.goal.type === 'page') goalsByPage.set(t.goal.page, [...(goalsByPage.get(t.goal.page) || []), t.id]);
  }
  const files = siteFiles(p).map((f) => {
    const exp = running.get(f.page!.id);
    const base: PageOptions = { ...o, item: f.item, fileName: f.name, abGoals: goalsByPage.get(f.page!.slug) };
    return { name: f.name, content: pageHTML(p, f.page!, exp ? { ...base, ab: { experimentId: exp.test.id, variant: 'a', goal: goalAttr(exp.test.goal) } } : base) };
  });
  for (const [pageId, { test, variant }] of running) {
    const page = p.pages.find((x) => x.id === pageId)!;
    const file = `${page.slug}.html`, variantFile = `_ab/${test.id}.html`;
    // The variant is served at the control's URL, so it keeps the control's slug, title and canonical link.
    const asControl: Page = { ...variant, slug: page.slug, title: variant.title || page.title, seo: page.seo };
    files.push({ name: variantFile, content: pageHTML(p, asControl, { ...o, fileName: file, ab: { experimentId: test.id, variant: 'b', goal: goalAttr(test.goal) } }) });
    experiments.push({ id: test.id, file, variantFile, split: Math.min(Math.max(test.split, 1), 99) });
  }
  files.push({ name: 'css/styles.css', content: siteCSS(p, o.minify) });
  if (o.siteUrl) {
    files.push({ name: 'sitemap.xml', content: sitemapXML(p, o.siteUrl) });
    files.push({ name: 'robots.txt', content: `User-agent: *\nAllow: /\nDisallow: /_ab/\n\nSitemap: ${o.siteUrl.replace(/\/?$/, '/')}sitemap.xml\n` });
  }
  return { files, experiments };
}
